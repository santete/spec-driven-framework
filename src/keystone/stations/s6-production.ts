// ── Stack detection + bootstrap dispatch ─────────────────────────

type StackLanguage = "typescript" | "python" | "go";

function detectStack(specs: SpecFile[]): StackLanguage {
  const project = specs.find((s) => s.data.type === "project");
  const stack = project?.data.stack as Record<string, unknown> | undefined;
  const lang = String(stack?.language ?? "typescript").toLowerCase();
  if (lang.includes("python")) return "python";
  if (lang.includes("go")) return "go";
  return "typescript";
}

function bootstrapCode(specs: SpecFile[], affectedIds: string[], runId: string, repoRoot: string): GeneratedFile[] {
  const affectedSet = new Set(affectedIds);
  const entSpecs = specs.filter((s) => s.data.type === "entity" && affectedSet.has(s.data.id));
  const reqSpecs = specs.filter((s) => s.data.type === "requirement" && affectedSet.has(s.data.id));
  const generatedFiles: GeneratedFile[] = [];
  const stack = detectStack(specs);

  for (const ent of entSpecs) {
    const generators = stack === "python"
      ? [generatePythonModel(ent, runId)]
      : [generateEntitySchema(ent, runId), generateEntityValidator(ent, runId)];
    for (const gen of generators) {
      const absPath = resolve(repoRoot, gen.path);
      mkdirSync(dirname(absPath), { recursive: true });
      writeFileSync(absPath, gen.content, "utf8");
      generatedFiles.push({ path: gen.path, owner_spec_id: ent.data.id, type: "implementation" });
    }
  }
  for (const req of reqSpecs) {
    const service = stack === "python" ? generatePythonService(req, runId) : generateService(req, runId);
    mkdirSync(dirname(resolve(repoRoot, service.path)), { recursive: true });
    writeFileSync(resolve(repoRoot, service.path), service.content, "utf8");
    generatedFiles.push({ path: service.path, owner_spec_id: req.data.id, type: "implementation" });

    const tests = stack === "python" ? generatePythonTests(req, runId) : generateTests(req, runId);
    mkdirSync(dirname(resolve(repoRoot, tests.path)), { recursive: true });
    writeFileSync(resolve(repoRoot, tests.path), tests.content, "utf8");
    generatedFiles.push({ path: tests.path, owner_spec_id: req.data.id, type: "test" });
  }
  return generatedFiles;
}

// ── Handler ───────────────────────────────────────────────────────

export function s6Handler(ctx: StationContext): StationOutcomeDraft {
  const impactPath = resolve(ctx.repoRoot, ".keystone", "impact-report.json");
  if (!existsSync(impactPath)) {
    return { verdict: "reject", message: "S6: impact-report.json missing" };
  }
  const impact: ImpactReport = JSON.parse(readFileSync(impactPath, "utf8"));

  if (impact.affected_ids.length === 0) {
    const report: ProductionReport = { run_id: ctx.runId, generated_files: [], verdict: "pass" };
    const outDir = resolve(ctx.repoRoot, ".keystone");
    mkdirSync(outDir, { recursive: true });
    writeFileSync(resolve(outDir, "production-report.json"), JSON.stringify(report, null, 2) + "\n", "utf8");
    return { verdict: "pass", message: "S6: No affected specs — skipping codegen.", report_path: ".keystone/production-report.json" };
  }

  let generatedFiles: GeneratedFile[];

  if (isBootstrap()) {
    // Bootstrap mode: template-generate code
    const specs = loadAllSpecs(resolve(ctx.repoRoot, "specs"), ctx.repoRoot);
    generatedFiles = bootstrapCode(specs, impact.affected_ids, ctx.runId, ctx.repoRoot);
  } else {
    // Validate mode: check if code exists with provenance
    const validation = validateGeneratedCode(ctx.repoRoot, impact.affected_ids);

    if (validation.files.length === 0) {
      return {
        verdict: "blocked",
        message: `S6: Awaiting code generation. Launch implementer + test-author subagents, then /keystone:resume. ${validation.issues.join("; ")}`,
      };
    }

    if (validation.issues.some((i) => i.includes("missing @keystone-owner"))) {
      return {
        verdict: "reject",
        message: `S6: Generated code has issues: ${validation.issues.join("; ")}`,
      };
    }

    generatedFiles = validation.files;
  }

  // Update ownership + trace index
  updateOwnership(ctx.repoRoot, generatedFiles);
  updateTraceIndex(ctx.repoRoot, generatedFiles);

  const report: ProductionReport = {
    run_id: ctx.runId,
    generated_files: generatedFiles,
    verdict: "pass",
  };
  const outDir = resolve(ctx.repoRoot, ".keystone");
  mkdirSync(outDir, { recursive: true });
  writeFileSync(resolve(outDir, "production-report.json"), JSON.stringify(report, null, 2) + "\n", "utf8");

  const implCount = generatedFiles.filter((f) => f.type === "implementation").length;
  const testCount = generatedFiles.filter((f) => f.type === "test").length;
  return {
    verdict: "pass",
    message: `S6: ${generatedFiles.length} file(s) validated (${implCount} impl, ${testCount} test).`,
    report_path: ".keystone/production-report.json",
  };
}
